#!/usr/bin/env python3
"""Regenerate the inlined splash logo in frontend/autoloader/app.js.

The autoloader page is generated by the remote loader's standalone builder,
which only embeds CSS and JS -- there is no image asset on the page to point
an <img> at. So the logo travels inside app.js as a data URI.

The source is assets/icon.svg, a full-bleed Illustrator export that wraps a
1024x1024 PNG as base64. That PNG is far too big to inline as-is (876KB, and
base64 inflates it by a third), so this script extracts it, scales it down and
palette-reduces it, then rewrites the data URI in app.js.

Transparency is the thing to be careful about: the source is genuinely
transparent (about 45% of its pixels are fully transparent), and palette
quantization keeps that alpha in the palette. Passing a transparency= index
to the PNG writer on top of it points tRNS at the wrong palette entry and
bakes the backdrop into opaque black. So: save the reduced image as-is and
verify the result instead of trusting it.

Dev tool only -- nothing in `make all` calls it. Requires Pillow:

    pip install Pillow
    python tools/make_splash_logo.py [--size 256] [--colors 192] [--check]

--check verifies what is currently inlined against the source and exits
non-zero on a mismatch, without writing anything.
"""

import argparse
import base64
import io
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MASTER = ROOT / "assets" / "icon.svg"
APP_JS = ROOT / "frontend" / "autoloader" / "app.js"

# data:image/png;base64,.... as it appears in app.js, up to the closing quote.
LOGO_RE = re.compile(r"(var LOGO = ')(data:image/png;base64,[A-Za-z0-9+/=]*)(';)")
PNG_IN_SVG_RE = re.compile(r'href="data:image/png;base64,([^"]+)"')


def load_pillow():
    try:
        from PIL import Image
    except ImportError:
        sys.exit(
            "Pillow is required to regenerate the logo: pip install Pillow\n"
            "(It is only needed for this dev tool, not for `make all`.)"
        )
    return Image


def source_png():
    """The PNG assets/icon.svg wraps, as PIL image, plus its byte size."""
    Image = load_pillow()
    text = MASTER.read_text(encoding="utf-8", errors="replace")
    match = PNG_IN_SVG_RE.search(text)
    if not match:
        sys.exit("Error: no embedded PNG found in %s" % MASTER)
    raw = base64.b64decode(match.group(1))
    return Image.open(io.BytesIO(raw)).convert("RGBA"), len(raw)


def transparent_fraction(im):
    alpha = im.getchannel("A")
    # get_flattened_data() is the modern accessor; getdata() is the old one.
    getter = getattr(alpha, "get_flattened_data", None) or alpha.getdata
    values = list(getter())
    return sum(1 for v in values if v == 0) / float(len(values))


def reduce_logo(im, size, colors):
    """Scale to `size` and palette-reduce, keeping the alpha channel intact."""
    Image = load_pillow()
    scaled = im.copy()
    scaled.thumbnail((size, size), Image.LANCZOS)
    # FASTOCTREE is the only quantizer that handles RGBA, and it keeps per
    # entry alpha in the palette. Saving mode P without a transparency= index
    # leaves the tRNS chunk alone, which is what we want.
    return scaled.quantize(colors=colors, method=Image.FASTOCTREE)


def encode(pil_image):
    buf = io.BytesIO()
    pil_image.save(buf, format="PNG", optimize=True)
    return buf.getvalue()


def verify(png_bytes, expected_fraction, label):
    """Fail loudly rather than shipping an opaque backdrop again."""
    Image = load_pillow()
    im = Image.open(io.BytesIO(png_bytes))
    if im.mode != "RGBA":
        im = im.convert("RGBA")
    corners = [im.getpixel(p) for p in ((0, 0), (im.width - 1, 0), (0, im.height - 1), (im.width - 1, im.height - 1))]
    if any(c[3] != 0 for c in corners):
        sys.exit(
            "Error: %s has an opaque backdrop (corner alpha %s).\n"
            "The source is transparent, so the reduction dropped its alpha -- "
            "do not pass a transparency= index when saving." % (label, [c[3] for c in corners])
        )
    got = transparent_fraction(im)
    if abs(got - expected_fraction) > 0.02:
        sys.exit(
            "Error: %s is %.1f%% transparent, expected about %.1f%%.\n"
            "The alpha channel did not survive the reduction." % (label, got * 100, expected_fraction * 100)
        )
    return im.width, im.height, got


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--size", type=int, default=256, help="longest edge in pixels (default 256)")
    ap.add_argument("--colors", type=int, default=192, help="palette entries (default 192)")
    ap.add_argument("--check", action="store_true", help="verify what is inlined; write nothing")
    args = ap.parse_args()

    if not MASTER.is_file():
        sys.exit("Error: %s not found" % MASTER)
    if not APP_JS.is_file():
        sys.exit("Error: %s not found" % APP_JS)

    original, original_bytes = source_png()
    original_fraction = transparent_fraction(original)
    print(
        "source: %dx%d, %d bytes, %.1f%% transparent"
        % (original.width, original.height, original_bytes, original_fraction * 100)
    )

    reduced = reduce_logo(original, args.size, args.colors)
    png_bytes = encode(reduced)
    width, height, fraction = verify(png_bytes, original_fraction, "reduced logo")
    print(
        "reduced: %dx%d, %d bytes (%d as base64), %.1f%% transparent"
        % (width, height, len(png_bytes), (len(png_bytes) * 4) // 3, fraction * 100)
    )

    app_js = APP_JS.read_text(encoding="utf-8")
    match = LOGO_RE.search(app_js)
    if not match:
        sys.exit("Error: no 'var LOGO = ...' data URI found in %s" % APP_JS)
    current = base64.b64decode(match.group(2).split(",", 1)[1])

    if args.check:
        verify(current, original_fraction, "inlined logo")
        if current == png_bytes:
            print("inlined logo is up to date (byte identical)")
            return 0
        print("inlined logo differs from a fresh reduction; run without --check to update it")
        return 1

    if current == png_bytes:
        print("inlined logo already up to date; nothing written")
        return 0

    uri = "data:image/png;base64," + base64.b64encode(png_bytes).decode("ascii")
    APP_JS.write_text(LOGO_RE.sub(lambda m: m.group(1) + uri + m.group(3), app_js, count=1),
                      encoding="utf-8", newline="")
    print("rewrote the LOGO data URI in %s" % APP_JS.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())